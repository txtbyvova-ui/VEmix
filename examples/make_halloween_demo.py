def sectioned_track(seconds: float, bpm: float, root: str, mode: str, energies: tuple[float, ...],
                    seed: int) -> np.ndarray:
    """Concatenate sections of different energy (each a synth_track slice) with short
    crossfades, so intensity changes inside the track."""
    n_sec = len(energies)
    seg = seconds / n_sec
    parts = [synth_track(seg + 1.0, bpm, root, mode, e, seed=seed * 10 + k) for k, e in enumerate(energies)]
    xf = int(0.5 * SR)
    out = parts[0]
    for p in parts[1:]:
        ramp = np.linspace(0, 1, xf)[:, None]
        out = np.concatenate([out[:-xf], out[-xf:] * (1 - ramp) + p[:xf] * ramp, p[xf:]])
    # level follows the section energy a little (quiet intros / breaks are quieter)
    t = np.arange(len(out)) / SR
    level = np.interp(t, np.linspace(0, len(out) / SR, n_sec), [0.55 + 0.45 * e for e in energies])
    out = out * level[:, None]
    return out / (np.max(np.abs(out)) + 1e-12)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("folder")
    ap.add_argument("--seconds", type=float, default=150.0, help="length of each track (default 150)")
    args = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    tools = find_ffmpeg()
    folder = Path(args.folder).resolve()
    folder.mkdir(parents=True, exist_ok=True)
    rows = ["rel_path,energy,mood,vibe_tags,approved,notes"]
    with tempfile.TemporaryDirectory() as tmp:
        for i, (artist, title, bpm, root, mode, sections, energy, mood, tags) in enumerate(TRACKS):
            data = master(sectioned_track(args.seconds, bpm, root, mode, sections, seed=i + 1), -1.0, 2.0)
            wav = Path(tmp) / f"{i}.wav"
            sf.write(str(wav), data, SR, subtype="FLOAT")
            name = f"{artist} - {title}.mp3"
            meta = {"artist": artist, "title": title, "genre": "halloween", "language": "en"}
            if artist == "Michael Jackson":
                meta["comment"] = PLACEHOLDER_NOTE
            encode(tools.ffmpeg, wav, folder / name, meta)
            rows.append(f"{name},{'' if energy is None else energy},{mood},{tags},true,"
                        + ("synthetic placeholder for the scenario anchor" if artist == "Michael Jackson" else
                           ("energy left to the analysis" if energy is None else "")))
            print(f"  {name}  ({bpm} BPM, {root} {mode}, sections {sections})")
    meta_path = folder.parent / "halloween_metadata.csv"
    meta_path.write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"Curator metadata: {meta_path}")
    print("Next: python automix.py analyze --folder", folder, "--segments --metadata", meta_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
